def bind_original_plans(snapshot):
    """Author explicit synthetic EAP1 fixtures before applying audit damage.

    This helper never runs in the reader/exporter. Native qualification uses
    original C++-generated bytes, not this model encoder.
    """
    from collections import defaultdict
    grouped = {}
    for name in ("effects", "postings", "children", "item_references"):
        grouped[name] = defaultdict(list)
        for row in snapshot[name]:
            grouped[name][row["operation_id"]].append(row)
    ledger = {(row["operation_id"], row["event_index"]): row for row in snapshot["ownership_events"]}
    origins = {row["uid"]: row for row in snapshot["item_origins"]}

    def position(row):
        if row.get("state") == "absent":
            return bytes(56)
        state = {"live": 1, "tombstone": 2, "quarantined": 3}[row["state"]]
        return struct.pack("<BB6xQQQQQH6x", row["owner"][0], state,
                           *row["owner"][1:], row["root"], row["parent"] or 0,
                           row["revision"], row.get("equipment_slot", 0))

    for operation in snapshot["operations"]:
        if operation["outcome"] != "committed":
            operation.update(canonical_plan=None, plan_digest=None)
            continue
        op = operation["operation_id"]
        effects = sorted(grouped["effects"][op], key=lambda row: row["account_index"])
        postings = sorted(grouped["postings"][op], key=lambda row: row["line_index"])
        children = sorted(grouped["children"][op], key=lambda row: row["child_index"])
        references = sorted(grouped["item_references"][op], key=lambda row: row["event_index"])
        accounts = [bytes.fromhex(row["account_key"]) + struct.pack("<8qQQ", *row["before"], *row["after"],
                    row["before_revision"], row["after_revision"]) for row in effects]
        lines = []
        for index, row in enumerate(postings):
            row["event_index"] = index
            lines.append(struct.pack("<IHH4qq", index, row["account_index"], row["child_index"],
                                     *row["delta"], row["copper_value"]))
        links = [bytes.fromhex(row["child_operation_id"]) + struct.pack("<IQHH", row["domain_id"],
                 row["discriminator"], row["parent_index"], row["relationship"]) for row in children]
        before, after, events = {}, {}, []
        for index, ref in enumerate(references):
            ref["line_index"] = index
            event = ledger[(ref["legacy_operation_id"], ref["legacy_event_index"])]
            origin = origins[ref["uid"]]
            prior = [row for row in snapshot["ownership_events"] if row["uid"] == ref["uid"] and
                     row["revision"] == ref["before_revision"]]
            old = {**(prior[0] if prior else origin), "revision": ref["before_revision"]}
            if "from_owner" in event:
                old["owner"] = event["from_owner"]
            else:
                event["from_owner"] = [7, 0, 0] if old.get("state") == "absent" else old["owner"]
            event.setdefault("from_equipment_slot", old.get("equipment_slot", 0))
            event.setdefault("to_equipment_slot", event.get("equipment_slot", 0))
            old["equipment_slot"] = event["from_equipment_slot"]
            new = {**event, "equipment_slot": event["to_equipment_slot"]}
            old_bytes, new_bytes = position(old), position(new)
            before.setdefault(ref["uid"], old_bytes)
            after[ref["uid"]] = new_bytes
            events.append(struct.pack("<IH2xQ", index, ref["child_index"], ref["uid"])+old_bytes+new_bytes)
        counts = (len(accounts), len(lines), len(links), len(before), len(after), len(events))
        intent = hashlib.sha256(b"synthetic EAP1 intent fixture" + bytes.fromhex(op)).digest()
        domain = hashlib.sha256(b"synthetic EAP1 domain fixture" + bytes.fromhex(op)).digest()
        header = bytearray(256)
        header[:4] = b"EAP1"
        struct.pack_into("<H", header, 4, 1)
        header[8:56] = bytes.fromhex(operation["lineage"] + operation["epoch"] + op)
        header[56:72] = bytes.fromhex(operation.get("original_operation_id") or "0" * 32)
        header[72] = 2 if 38 <= operation["reason"] <= 42 else 1
        struct.pack_into("<QIIIH", header, 76, 7, 1, 1, 1, operation["reason"])
        source = operation.get("source_event")
        if source:
            header[100], header[104:152] = 1, bytes.fromhex(source)
        header[152:184], header[184:216] = intent, domain
        struct.pack_into("<6I", header, 216, *counts)
        witness = lambda rows: [struct.pack("<Q", uid)+value for uid, value in rows.items()]
        encoded = bytes(header)+b"".join(accounts+lines+links+witness(before)+witness(after)+events)
        operation.update(accounting_version=1, writer_id=1, policy_version=1, compiler_version=1,
                         actor_kind=header[72], actor_id=7, before_witness_count=counts[3], after_witness_count=counts[4],
                         intent_digest=intent.hex(), domain_digest=domain.hex(),
                         plan_digest=hashlib.sha256(encoded).hexdigest(), canonical_plan=encoded.hex())
    return snapshot


